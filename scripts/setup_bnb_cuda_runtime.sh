#!/usr/bin/env bash
# Make bitsandbytes 0.37.2 load the CUDA binary that matches torch's own CUDA runtime.
#
# bitsandbytes 0.37.2 uses the first libcudart.so it finds: in $CONDA_PREFIX/lib, else in the
# LD_LIBRARY_PATH directories (collected into a set, so with several matches the pick is
# arbitrary and can change between runs), else in /usr/local/cuda/lib64. It then loads
# libbitsandbytes_cuda<version of that runtime>.so. On the VESSL image the system runtime is CUDA
# 12.8 (also on the image's LD_LIBRARY_PATH), so it looked for libbitsandbytes_cuda128.so, which
# 0.37.2 does not ship, and the import failed. torch 2.0.0+cu117 brings its own CUDA 11.7 runtime
# as the nvidia-cuda-runtime-cu11 wheel; this script
#   1. links that runtime as $CONDA_PREFIX/lib/libcudart.so, which bitsandbytes checks first, so
#      the system CUDA is never considered;
#   2. writes conda activate.d / deactivate.d hooks that put the pip nvidia-* lib directories first
#      on LD_LIBRARY_PATH (and restore the previous value on deactivate), so the setting survives
#      new terminals and tmux.
# Everything is derived from torch.version.cuda, never from nvidia-smi or /usr/local/cuda. Safe to
# re-run. Run it inside the activated conda env; afterwards `source` the activate hook (or
# re-activate the env) to apply LD_LIBRARY_PATH in the calling shell, and check the result with
# scripts/verify_bnb_cuda.py.
set -euo pipefail

: "${CONDA_PREFIX:?activate the conda env first (conda activate ilora)}"

eval "$(python - <<'PYEOF'
import importlib.util, os, shlex, sys, sysconfig
import torch
spec = importlib.util.find_spec('bitsandbytes')
values = {
    'PY_PREFIX': sys.prefix,
    'TORCH_VERSION': torch.__version__,
    'TORCH_CUDA': torch.version.cuda or '',
    'SITE_PACKAGES': sysconfig.get_paths()['purelib'],
    'BNB_DIR': os.path.dirname(spec.origin) if spec else '',
}
for key, value in values.items():
    print(f'{key}={shlex.quote(value)}')
PYEOF
)"

fatal() { echo "FATAL: $*" >&2; exit 1; }

[[ "$PY_PREFIX" -ef "$CONDA_PREFIX" ]] || fatal "python ($PY_PREFIX) is not the active conda env ($CONDA_PREFIX)."
[[ -n "$TORCH_CUDA" ]] || fatal "torch $TORCH_VERSION is a CPU build; requirements.txt pins the CUDA 11.7 build."
[[ -n "$BNB_DIR" ]] || fatal "bitsandbytes is not installed in this env."

CUDA_MAJOR="${TORCH_CUDA%%.*}"
CUDA_TAG="${TORCH_CUDA//./}"
EXPECTED_BINARY="$BNB_DIR/libbitsandbytes_cuda${CUDA_TAG}.so"
[[ -f "$EXPECTED_BINARY" ]] || fatal "bitsandbytes has no binary for torch's CUDA $TORCH_CUDA ($EXPECTED_BINARY)."

NVIDIA_DIR="$SITE_PACKAGES/nvidia"
CUDART="$(find "$NVIDIA_DIR/cuda_runtime/lib" -maxdepth 1 -name "libcudart.so.${CUDA_MAJOR}*" \
    \( -type f -o -type l \) 2>/dev/null | sort | head -n 1)"
[[ -n "$CUDART" ]] || fatal "no libcudart.so.${CUDA_MAJOR}* under $NVIDIA_DIR/cuda_runtime/lib (nvidia-cuda-runtime wheel missing?)."

echo "  torch $TORCH_VERSION, torch.version.cuda $TORCH_CUDA -> runtime $CUDART, bitsandbytes binary $(basename "$EXPECTED_BINARY")"

# 1. $CONDA_PREFIX/lib/libcudart.so -> torch's runtime
LINK="$CONDA_PREFIX/lib/libcudart.so"
mkdir -p "$CONDA_PREFIX/lib"
if [[ -e "$LINK" && ! -L "$LINK" ]]; then
    fatal "$LINK is a real file (a conda CUDA toolkit?) and bitsandbytes would use it; remove it or use a fresh env."
fi
if [[ "$(readlink "$LINK" 2>/dev/null || true)" == "$CUDART" ]]; then
    echo "  $LINK already points to it."
else
    ln -sfn "$CUDART" "$LINK"
    echo "  linked $LINK -> $CUDART"
fi

# 2. activation hooks. $CONDA_PREFIX/lib itself is not put on LD_LIBRARY_PATH: bitsandbytes checks
# it directly, and on LD_LIBRARY_PATH it makes system binaries (e.g. tmux) load the env's libraries.
CUDA_LIBS="$(find "$NVIDIA_DIR" -mindepth 2 -maxdepth 2 -type d -name lib | sort | paste -sd: -)"
ACTIVATE_DIR="$CONDA_PREFIX/etc/conda/activate.d"
DEACTIVATE_DIR="$CONDA_PREFIX/etc/conda/deactivate.d"
mkdir -p "$ACTIVATE_DIR" "$DEACTIVATE_DIR"
rm -f "$ACTIVATE_DIR/ilora_bnb_cuda117.sh"  # older hook from setup_vessl.sh, prepended without restoring
cat > "$ACTIVATE_DIR/ilora_bnb_cuda.sh" <<EOF
# Generated by scripts/setup_bnb_cuda_runtime.sh: the CUDA $TORCH_CUDA libraries torch was built with
# (pip nvidia-* wheels) come first on LD_LIBRARY_PATH. Re-activating does not stack entries.
if [ -z "\${_ILORA_SAVED_LD_LIBRARY_PATH+x}" ]; then
    export _ILORA_SAVED_LD_LIBRARY_PATH="\${LD_LIBRARY_PATH-}"
fi
export LD_LIBRARY_PATH="$CUDA_LIBS\${_ILORA_SAVED_LD_LIBRARY_PATH:+:\$_ILORA_SAVED_LD_LIBRARY_PATH}"
EOF
cat > "$DEACTIVATE_DIR/ilora_bnb_cuda.sh" <<'EOF'
# Generated by scripts/setup_bnb_cuda_runtime.sh: restore LD_LIBRARY_PATH from before activation.
if [ -n "${_ILORA_SAVED_LD_LIBRARY_PATH+x}" ]; then
    if [ -n "$_ILORA_SAVED_LD_LIBRARY_PATH" ]; then
        export LD_LIBRARY_PATH="$_ILORA_SAVED_LD_LIBRARY_PATH"
    else
        unset LD_LIBRARY_PATH
    fi
    unset _ILORA_SAVED_LD_LIBRARY_PATH
fi
EOF
echo "  wrote $ACTIVATE_DIR/ilora_bnb_cuda.sh and $DEACTIVATE_DIR/ilora_bnb_cuda.sh"
